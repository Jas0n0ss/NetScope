export function detectLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED.includes(stored)) return stored;
  } catch {
    /* storage may be blocked */
  }
  const languages = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  return languages.some((language) => String(language).toLowerCase().startsWith('zh')) ? 'zh' : 'en';
}

export function getLanguage() {
  return current;
}

export function getLocale() {
  return current === 'zh' ? 'zh-CN' : 'en';
}

export function isChinese() {
  return current === 'zh';
}

export function setLanguage(language, { reload = true } = {}) {
  const next = SUPPORTED.includes(language) ? language : 'en';
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* ignore */
  }
  current = next;
  document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en';
  if (reload) {
    window.location.reload();
    return;
  }
  translateDOM(document);
  syncLanguageControls();
}

function interpolate(template, vars) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => (
    vars[key] === undefined || vars[key] === null ? match : String(vars[key])
  ));
}

/** Translate a known English source string, with optional {placeholder} values. */
export function t(source, vars) {
  const template = current === 'zh' && ZH[source] ? ZH[source] : source;
  return interpolate(template, vars);
}

/** Translate a raw string if it exactly matches a dictionary entry. */
export function translateString(value) {
  if (current !== 'zh' || typeof value !== 'string') return value;
  const translated = ZH[value.trim()];
  if (!translated) return value;
  const leading = value.match(/^\s*/)?.[0] || '';
  const trailing = value.match(/\s*$/)?.[0] || '';
  return `${leading}${translated}${trailing}`;
}

const SKIP_SELECTOR = 'script, style, pre, code, textarea, [data-i18n-ignore], .no-i18n';

function translateTextNode(node) {
  if (!node.nodeValue || !node.nodeValue.trim()) return;
  if (node.parentElement?.closest(SKIP_SELECTOR)) return;
  const next = translateString(node.nodeValue);
  if (next !== node.nodeValue) node.nodeValue = next;
}

function translateAttribute(element, name) {
  if (!element.hasAttribute?.(name)) return;
  if (element.closest?.(SKIP_SELECTOR)) return;
  const value = element.getAttribute(name);
  if (!value) return;
  const next = translateString(value);
  if (next !== value) element.setAttribute(name, next);
}

const ATTRS = ['placeholder', 'aria-label', 'title', 'alt'];

/** Translate static and dynamically inserted DOM content. */
export function translateDOM(root = document) {
  if (current !== 'zh' || !root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node);
    node = walker.nextNode();
  }
  if (root.nodeType === Node.ELEMENT_NODE) {
    ATTRS.forEach((name) => translateAttribute(root, name));
  }
  if (root.querySelectorAll) {
    root.querySelectorAll(ATTRS.map((name) => `[${name}]`).join(',')).forEach((element) => {
      ATTRS.forEach((name) => translateAttribute(element, name));
    });
  }
}

export function syncLanguageControls() {
  document.querySelectorAll('[data-lang-toggle]').forEach((button) => {
    button.textContent = current === 'zh' ? 'EN' : '中文';
    button.setAttribute('aria-label', current === 'zh' ? '切换到英文' : 'Switch to Chinese');
    button.setAttribute('title', current === 'zh' ? '切换到英文' : 'Switch to Chinese');
  });
  document.querySelectorAll('input[name="lang"]').forEach((radio) => {
    radio.checked = radio.value === current;
  });
}

export function initI18n() {
  current = detectLanguage();
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
  translateDOM(document);
  syncLanguageControls();

  document.addEventListener('click', (event) => {
    const toggle = event.target.closest('[data-lang-toggle]');
    if (toggle) setLanguage(current === 'zh' ? 'en' : 'zh');
  });

  document.addEventListener('change', (event) => {
    if (event.target.matches?.('input[name="lang"]')) setLanguage(event.target.value);
  });

  if (current === 'zh' && !observer) {
    observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === 'childList') {
          mutation.addedNodes.forEach((node) => translateDOM(node));
        } else if (mutation.type === 'characterData') {
          translateTextNode(mutation.target);
        } else if (mutation.type === 'attributes') {
          translateAttribute(mutation.target, mutation.attributeName);
        }
      }
    });
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ATTRS,
    });
  }
}
