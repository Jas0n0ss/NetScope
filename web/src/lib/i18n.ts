import { useCallback, useSyncExternalStore } from 'react';

export type Lang = 'en' | 'zh';

const KEY = 'netscope.v2.lang';
const listeners = new Set<() => void>();

const detect = (): Lang => {
  try {
    const stored = localStorage.getItem(KEY);
    if (stored === 'en' || stored === 'zh') return stored;
  } catch {
    /* storage may be unavailable */
  }
  return 'en';
};

let current: Lang = detect();

const apply = (lang: Lang) => {
  if (typeof document !== 'undefined') document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
};

if (typeof document !== 'undefined') apply(current);

export const getLang = (): Lang => current;

export function setLang(lang: Lang): void {
  current = lang;
  apply(lang);
  try {
    localStorage.setItem(KEY, lang);
  } catch {
    /* storage may be unavailable */
  }
  listeners.forEach((listener) => listener());
}

export const toggleLang = (): Lang => {
  setLang(current === 'zh' ? 'en' : 'zh');
  return current;
};

const subscribe = (listener: () => void): (() => void) => {
  listeners.add(listener);
  return () => listeners.delete(listener);
};

const interpolate = (text: string, vars?: Record<string, string | number>): string => {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, key: string) => (key in vars ? String(vars[key]) : match));
};

export function translate(text: string, vars?: Record<string, string | number>): string {
  const value = current === 'zh' ? ZH[text] ?? text : text;
  return interpolate(value, vars);
}

export const useLang = (): Lang => useSyncExternalStore(subscribe, getLang, getLang);

export const useT = () => {
  const lang = useSyncExternalStore(subscribe, getLang, getLang);
  return useCallback(
    (text: string, vars?: Record<string, string | number>) => {
      const value = lang === 'zh' ? ZH[text] ?? text : text;
      return interpolate(value, vars);
    },
    [lang],
  );
};

export type TFn = (text: string, vars?: Record<string, string | number>) => string;

export function emailDetail(detail: string, t: TFn): string {
  const multiple = detail.match(/^Multiple SPF records \((\d+)\)/);
  if (multiple) return t('{n} SPF records — receivers may ignore all of them.', { n: multiple[1] });
  const published = detail.match(/^Key published at (.*?)\.$/);
  if (published) return t('Key published at {selector}.', { selector: published[1] });
  const missingKey = detail.match(/^No key at (.*?) — /);
  if (missingKey) return t('No key at {selector} — messages cannot be cryptographically verified.', { selector: missingKey[1] });
  const policy = detail.match(/^Policy p=([a-z]+)/i);
  if (policy) {
    return policy[1] === 'none'
      ? t('Policy p=none — reports only, no enforcement.')
      : t('Policy p={policy} — spoofed mail is handled.', { policy: policy[1] });
  }
  return t(detail);
}

export function headerDetail(detail: string, t: TFn): string {
  const present = detail.match(/^Present · (\d+) characters$/);
  if (present) return t('Present · {n} characters', { n: present[1] });
  return t(detail);
}

export function toolNote(note: string, t: TFn): string {
  const hosts = note.match(/^([\d,]+) usable host addresses\.$/);
  if (hosts) return t('{n} usable host addresses.', { n: hosts[1] });
  const total = note.match(/^2\^(\d+) total addresses in this prefix\.$/);
  if (total) return t('2^{n} total addresses in this prefix.', { n: total[1] });
  return t(note);
}

